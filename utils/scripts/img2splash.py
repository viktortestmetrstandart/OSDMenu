import sys
from PIL import Image

if len(sys.argv) < 3:
    print("Usage: img2splash.py <input_image> <output_header> [width] [height]")
    sys.exit(1)

in_path = sys.argv[1]
out_path = sys.argv[2]
target_w = int(sys.argv[3]) if len(sys.argv) > 3 else 320
target_h = int(sys.argv[4]) if len(sys.argv) > 4 else 200

resample_filter = getattr(Image, "Resampling", Image).LANCZOS
img = Image.open(in_path).convert("RGBA").resize((target_w, target_h), resample_filter)
w, h = img.size
pixels = img.load()

with open(out_path, "w") as f:
    f.write(f"// Generated by img2splash.py from {in_path}\n")
    f.write("#include <stdint.h>\n\n")
    f.write(f"uint32_t splashWidth = {w};\n")
    f.write(f"uint32_t splashHeight = {h};\n\n")
    f.write('uint32_t __attribute__((aligned(16))) __attribute__((section("._splash"))) splash[] = {\n')
    for y in range(h):
        f.write(f"    // row {y}\n")
        for x in range(w):
            r, g, b, a = pixels[x, y]
            r = (r * a) // 255
            g = (g * a) // 255
            b = (b * a) // 255
            val = (b << 16) | (g << 8) | r
            f.write(f"    0x{val:08x},\n")
    f.write("};\n")

print(f"Generated {out_path} ({w}x{h})")
